export const ENTITY_GUESSER_VALUE_COPY = Object.freeze(
    Object.fromEntries(VALUE_ENTRIES.map(([key, ...values]) => [
        key,
        Object.freeze(Object.fromEntries(
            LOCALE_ORDER.map((locale, index) => [locale, values[index]])
        ))
    ]))
);

const VALUE_JOINERS = Object.freeze({
    en: ' & ',
    nl: ' & ',
    fr: ' et ',
    de: ' und ',
    es: ' y '
});

export function resolveEntityLocale(locale = 'en') {
    const code = String(locale || 'en').slice(0, 2).toLowerCase();
    return LOCALE_ORDER.includes(code) ? code : 'en';
}

export function localizeEntityValue(value, locale = 'en') {
    const language = resolveEntityLocale(locale);
    if (Array.isArray(value)) {
        return value.map(item => localizeEntityValue(item, language)).join(VALUE_JOINERS[language]);
    }
    if (typeof value === 'boolean') return ENTITY_GUESSER_VALUE_COPY[value ? 'Yes' : 'No'][language];
    if (value === null || value === undefined || value === '') {
        return ENTITY_GUESSER_VALUE_COPY['N/A'][language];
    }
    const copy = ENTITY_GUESSER_VALUE_COPY[String(value)];
    return copy?.[language] || copy?.en || String(value);
}

export function formatLocalizedValue(value, locale = 'en') {
    return localizeEntityValue(value, locale);
}
