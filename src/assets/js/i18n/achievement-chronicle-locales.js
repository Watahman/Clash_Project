function collectionText(rows) {
    return Object.fromEntries(Object.entries(rows).flatMap(([key, [title, description, badge]]) => [
        [`achievements.collection.${key}.title`, title],
        [`achievements.collection.${key}.description`, description],
        [`achievements.collection.${key}.badge`, badge]
    ]));
}

