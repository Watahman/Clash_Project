export function bracketText(key, params = {}) {
    let value = copy[getLanguage()]?.[key] || copy.en[key] || key;
    Object.entries(params).forEach(([name, replacement]) => {
        value = value.replaceAll(`{${name}}`, replacement ?? '');
    });
    return value;
}
