import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { workspaceLocales } from '../src/assets/js/i18n/workspace-locales.js';
import { publicPageLocales } from '../src/assets/js/i18n/public-pages-locales.js';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputDirectory = path.join(projectRoot, 'src', 'assets', 'js', 'i18n', 'runtime-locales');
const languageCodes = ['nl', 'en', 'fr', 'de', 'es'];

await mkdir(outputDirectory, { recursive: true });

for (const [area, dictionaries] of Object.entries({ workspace: workspaceLocales, public: publicPageLocales })) {
    for (const language of languageCodes) {
        const output = `// Generated by npm run generate:i18n.\nexport default Object.freeze(${JSON.stringify(dictionaries[language], null, 4)});\n`;
        await writeFile(path.join(outputDirectory, `${area}-${language}.js`), output, 'utf8');
    }
}

console.log(`Generated ${languageCodes.length * 2} runtime locale modules.`);
